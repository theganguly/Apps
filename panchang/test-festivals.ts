const failures: string[] = [];
for (const [dateStr, needle] of CASES) {
  const [d, m, y] = dateStr.split('-').map(Number);
  const p = dayPanchang(y, m, d, LAT, LON);
  const fests = festivalsOfDay(p, { sankrantis, lat: LAT, lon: LON });
  const names = fests.map((f) => f.gu).join(' | ');
  if (names.includes(needle)) { pass++; }
  else { fail++; failures.push(`${dateStr}: expected "${needle}" — got [${names}]  (tithi ${p.tithiFull} ${p.paksha} ${p.tithi}, month ${p.monthIdx})`); }
}
